using System.Globalization;
using System.Text;
using Hokusai.Core;
using Hokusai.Runtime;

namespace Hokusai.Generate;

/// <summary>Names derived from an action for the different surfaces.</summary>
public sealed record ActionNames(string Display, string Pascal, string Route, string Tool)
{
    public static ActionNames For(string action)
    {
        var camel = Infer.Naming.Camel(action);
        var pascal = Infer.Naming.Pascal(camel);
        var words = action.Trim().ToLowerInvariant().Split([' ', '-', '_'], StringSplitOptions.RemoveEmptyEntries);
        return new ActionNames(action, pascal, string.Join('-', words), string.Join('_', words));
    }
}

/// <summary>
/// Emits the straight-line C# for one action: input records, validation, and execution built on the same
/// runtime primitives the verifier's interpreter uses.
/// </summary>
public sealed class CSharpEmitter(ActionTemplate template, string ns, string? disabledReason)
{
    private readonly ActionNames _names = ActionNames.For(template.Name);
    private readonly StringBuilder _sb = new();
    private int _indent;

    public static string Lit(string? value)
    {
        if (value is null)
        {
            return "null";
        }

        var sb = new StringBuilder("\"");
        foreach (var c in value)
        {
            sb.Append(c switch
            {
                '\\' => "\\\\",
                '"' => "\\\"",
                '\r' => "\\r",
                '\n' => "\\n",
                '\t' => "\\t",
                _ when char.IsControl(c) => "\\u" + ((int)c).ToString("X4", CultureInfo.InvariantCulture),
                _ => c.ToString(),
            });
        }

        return sb.Append('"').ToString();
    }

    public static string Bool(bool b) => b ? "true" : "false";

    public static string ClrNullable(string clr) => clr switch
    {
        "string" => "string?",
        _ => clr + "?",
    };

    private void Line(string text = "")
    {
        if (text.Length == 0)
        {
            _sb.AppendLine();
            return;
        }

        _sb.Append(' ', _indent * 4).AppendLine(text);
    }

    private void Open(string text)
    {
        Line(text);
        Line("{");
        _indent++;
    }

    private void Close(string suffix = "")
    {
        _indent--;
        Line("}" + suffix);
    }

    private static string Doc(string? text) =>
        (text ?? "").Replace("&", "&amp;", StringComparison.Ordinal).Replace("<", "&lt;", StringComparison.Ordinal).Replace(">", "&gt;", StringComparison.Ordinal);

    private static string Prop(TemplateParameter p) => Infer.Naming.Pascal(p.Name);

    private string ItemType(InputList c) => _names.Pascal + Infer.Naming.Pascal(c.Name) + "Item";

    public string InputType => _names.Pascal + "Input";

    public string RowType => _names.Pascal + "Row";

    public string Emit()
    {
        Line("// <auto-generated>");
        Line($"//   Generated by Hokusai from {template.DemonstrationCount} demonstration(s) of \"{template.Name}\". Regenerate instead of editing.");
        Line("// </auto-generated>");
        Line("#nullable enable");
        Line("using System.Data.Common;");
        Line("using Hokusai.Runtime;");
        Line();
        Line($"namespace {ns};");
        Line();
        EmitInputs();
        if (template.Kind == ActionKind.Read && template.ResultColumns.Count > 0)
        {
            Line($"/// <summary>One row returned by <c>{Doc(template.Name)}</c>.</summary>");
            Line($"public sealed record {RowType}({string.Join(", ", template.ResultColumns.Select(c => $"{ClrNullable(c.ClrType)} {Infer.Naming.Pascal(Infer.Naming.Camel(c.Name))}"))});");
            Line();
        }

        EmitAction();
        return _sb.ToString();
    }

    private void EmitInputs()
    {
        foreach (var c in template.Collections)
        {
            Line($"/// <summary>One row of '{Doc(c.Label ?? c.Name)}'.</summary>");
            Open($"public sealed record {ItemType(c)}");
            foreach (var p in template.Parameters.Where(p => p.Collection == c.Name))
            {
                EmitProperty(p);
            }

            Close();
            Line();
        }

        Line($"/// <summary>Inputs of <c>{Doc(template.Name)}</c>.</summary>");
        Open($"public sealed record {InputType}");
        foreach (var p in template.Parameters.Where(p => p.Collection is null))
        {
            EmitProperty(p);
        }

        foreach (var c in template.Collections)
        {
            Line($"/// <summary>Rows of '{Doc(c.Label ?? c.Name)}'.</summary>");
            Line($"public IReadOnlyList<{ItemType(c)}>? {Infer.Naming.Pascal(c.Name)} {{ get; init; }}");
        }

        Close();
        Line();
    }

    private void EmitProperty(TemplateParameter p)
    {
        Line($"/// <summary>{Doc(ParameterDescription(p))}</summary>");
        Line($"public {ClrNullable(p.ClrType)} {Prop(p)} {{ get; init; }}");
    }

    public static string ParameterDescription(TemplateParameter p)
    {
        var parts = new List<string> { p.Label is { Length: > 0 } ? $"'{p.Label.TrimEnd(':')}'" : p.Name };
        if (p.Lookup is not null)
        {
            parts.Add($"a {p.Lookup.Table} {p.Lookup.DisplayColumn}, resolved to {p.Lookup.Table}.{p.Lookup.KeyColumn}");
        }
        else if (p.TargetColumn is not null)
        {
            parts.Add("stored in " + p.TargetColumn);
        }

        if (p.MaxLength is int max)
        {
            parts.Add($"max {max} characters");
        }

        if (p.ClrType == "bool")
        {
            parts.Add("checkbox");
        }

        return string.Join("; ", parts) + (p.Required ? " (required)" : "");
    }

    private void EmitAction()
    {
        var verified = template.Status == TemplateStatus.Verified;
        Line($"/// <summary>{Doc(template.Description ?? template.Name)}</summary>");
        Open($"public static class {_names.Pascal}Action");
        Open("public static ActionInfo Info { get; } = new()");
        Line($"Name = {Lit(_names.Route)},");
        Line($"DisplayName = {Lit(template.Name)},");
        Line($"Tool = {Lit(_names.Tool)},");
        Line($"Description = {Lit(Describe())},");
        Line($"IsWrite = {Bool(template.Kind == ActionKind.Write)},");
        Line($"Destructive = {Bool(template.Destructive)},");
        Line($"Verified = {Bool(verified && disabledReason is null)},");
        Line($"DisabledReason = {Lit(disabledReason)},");
        Line($"Provider = ProviderKind.{template.Provider},");
        Line($"Tables = [{string.Join(", ", template.Tables.Select(Lit))}],");
        Line($"Fingerprint = {Lit(template.SchemaFingerprint)},");
        Line($"GeneratedColumns = [{string.Join(", ", template.GeneratedColumns.Select(Lit))}],");
        _indent--;
        Line("};");
        Line();

        foreach (var s in template.AllStatements())
        {
            Line($"private const string Sql{s.Id} = {Lit(s.Sql)};");
        }

        if (template.FileOutput is { } file)
        {
            Line();
            Open("private static readonly CsvSpec Csv = new()");
            Line($"Delimiter = {Lit(file.Csv.Delimiter)},");
            Line($"Header = {Bool(file.Csv.Header)},");
            Line($"HeaderNames = [{string.Join(", ", file.Csv.HeaderNames.Select(Lit))}],");
            Line($"NewLine = {Lit(file.Csv.NewLine)},");
            Line($"QuoteAll = {Bool(file.Csv.QuoteAll)},");
            Line($"TrailingNewLine = {Bool(file.Csv.TrailingNewLine)},");
            Line($"Columns = [{string.Join(", ", file.Csv.Columns.Select(c => $"new CsvColumn {{ SourceColumn = {Lit(c.SourceColumn)}, Format = {Lit(c.Format)} }}"))}],");
            _indent--;
            Line("};");
        }

        Line();
        EmitValidate();
        Line();
        EmitExecute();
        Close();
    }

    private string Describe()
    {
        var sb = new StringBuilder();
        sb.Append(template.Kind == ActionKind.Write ? "Writes to the database: " : "Reads from the database: ");
        sb.Append(template.Name).Append('.');
        if (template.Destructive)
        {
            sb.Append(" DESTRUCTIVE: deletes rows.");
        }

        if (template.FileOutput is not null)
        {
            sb.Append(" Returns the CSV file the app exported.");
        }

        var inputs = template.Parameters.Where(p => p.Label is not null).Select(p => p.Label!.TrimEnd(':')).ToList();
        if (inputs.Count > 0)
        {
            sb.Append(" Inputs correspond to the form fields ").Append(string.Join(", ", inputs.Select(i => "'" + i + "'"))).Append('.');
        }

        sb.Append(CultureInfo.InvariantCulture, $" Learned from {template.DemonstrationCount} demonstration(s)");
        sb.Append(template.Status == TemplateStatus.Verified ? " and verified by replay." : "; not verified.");
        return sb.ToString();
    }

    private void EmitValidate()
    {
        Open($"public static List<string> Validate({InputType} input)");
        Line("var errors = new List<string>();");
        foreach (var p in template.Parameters.Where(p => p.Collection is null))
        {
            EmitChecks(p, "input." + Prop(p), Lit(p.Name));
        }

        foreach (var c in template.Collections)
        {
            var prop = "input." + Infer.Naming.Pascal(c.Name);
            Open($"if ({prop} is null)");
            Line($"errors.Add({Lit(c.Name + " is required.")});");
            Close();
            Open("else");
            Open($"for (var i = 0; i < {prop}.Count; i++)");
            Line($"var item = {prop}[i];");
            foreach (var p in template.Parameters.Where(p => p.Collection == c.Name))
            {
                EmitChecks(p, "item." + Prop(p), $"$\"{c.Name}[{{i}}].{p.Name}\"");
            }

            Close();
            Close();
        }

        Line("return errors;");
        Close();
    }

    private void EmitChecks(TemplateParameter p, string access, string nameExpr)
    {
        if (p.Required || p.Lookup is not null)
        {
            Line($"if ({access} is null) errors.Add({nameExpr} + \" is required.\");");
        }

        if (p.MaxLength is int max && p.ClrType == "string")
        {
            Line($"if ({access} is {{ Length: > {max} }}) errors.Add({nameExpr} + \" must be at most {max} characters.\");");
        }
    }

    private void EmitExecute()
    {
        Line($"public static async Task<ActionOutcome> ExecuteAsync(DbConnection? connection, DbTransaction? transaction, ProviderKind provider, {InputType} input, bool dryRun, CancellationToken ct)");
        Line("{");
        _indent++;
        Line("var run = new HkRun(connection, transaction, provider, dryRun);");
        var fks = template.Parameters.Where(p => p.Collection is null && p.Lookup is null && p.ForeignKey is not null).ToList();
        if (fks.Count > 0)
        {
            Open("if (!dryRun)");
            foreach (var p in fks)
            {
                var dot = p.ForeignKey!.LastIndexOf('.');
                Line($"await HkLookup.EnsureExistsAsync(connection!, transaction, provider, {Lit(p.ForeignKey[..dot])}, {Lit(p.ForeignKey[(dot + 1)..])}, input.{Prop(p)}, {Lit(p.Name)}, ct);");
            }

            Close();
        }

        EmitSteps(template.Steps, inLoop: false);
        Line("return new ActionOutcome");
        Line("{");
        _indent++;
        Line("Plan = run.Plan,");
        Line("RowsAffected = run.RowsAffected,");
        if (template.Kind == ActionKind.Read && template.ResultStep is int rs && template.ResultColumns.Count > 0)
        {
            var args = string.Join(", ", template.ResultColumns.Select(c => $"HkConvert.To<{ClrNullable(c.ClrType)}>(r{rs}, row, {Lit(c.Name)})"));
            Line($"Rows = r{rs} is null ? null : r{rs}.Rows.Select(row => (object)new {RowType}({args})).ToList(),");
        }

        if (template.FileOutput is { } file)
        {
            Line($"File = r{file.SourceStep} is null ? null : CsvOutput.Write(Csv, r{file.SourceStep}),");
        }

        _indent--;
        Line("};");
        Close();
    }

    private void EmitSteps(List<TemplateStep> steps, bool inLoop)
    {
        foreach (var step in steps)
        {
            switch (step)
            {
                case StatementStep s:
                    var args = s.Bindings.Select(b => Arg(b, s)).ToList();
                    Line($"var r{s.Id} = await run.ExecuteAsync({s.Id}, Sql{s.Id}, [{string.Join(", ", args)}], ct);");
                    break;
                case ConditionalStep c:
                    Line($"// Runs when {c.Condition.Description}.");
                    Open($"if ({ConditionExpression(c.Condition)})");
                    EmitSteps(c.Body, inLoop);
                    Close();
                    break;
                case LoopStep l:
                    var collection = template.Collections.FirstOrDefault(c => c.Name == l.Collection);
                    Open($"foreach (var item in input.{Infer.Naming.Pascal(collection?.Name ?? "lines")} ?? [])");
                    EmitSteps(l.Body, inLoop: true);
                    Close();
                    break;
            }
        }
    }

    private string Access(string parameter)
    {
        var p = template.Parameter(parameter)!;
        return (p.Collection is null ? "input." : "item.") + Prop(p);
    }

    private static string Enc(ValueEncoding e) =>
        e.Format is null ? $"ValueEncoding.Of(EncodingKind.{e.Kind})" : $"ValueEncoding.Of(EncodingKind.{e.Kind}, {Lit(e.Format)})";

    private string Arg(Binding b, StatementStep s)
    {
        var name = Lit(b.Placeholder.TrimStart('@'));
        switch (b.Kind)
        {
            case BindingKind.Input:
                var p = template.Parameter(b.Parameter!)!;
                if (p.Lookup is { } l)
                {
                    return $"new HkLookupArg({name}, {Lit(l.Table)}, {Lit(l.KeyColumn)}, {Lit(l.DisplayColumn)}, {Access(p.Name)})";
                }

                return $"new HkValueArg({name}, HkEncode.Encode({Enc(b.Encoding)}, {Access(p.Name)}))";
            case BindingKind.Dependent:
                return $"new HkDeferredArg({name}, {Lit($"(result of step {b.SourceStep}: {b.SourceColumn})")}, () => HkEncode.Encode({Enc(b.Encoding)}, r{b.SourceStep}!.Value(0, {Lit(b.SourceColumn)})))";
            case BindingKind.Generated:
                return $"new HkValueArg({name}, HkEncode.Encode({Enc(b.Encoding)}, HkGenerate.Value({Lit(b.Generator)})))";
            default:
                var value = b.ConstantType switch
                {
                    "null" => "null",
                    "number" => decimal.Parse(b.Constant!, NumberStyles.Float, CultureInfo.InvariantCulture).ToString(CultureInfo.InvariantCulture) + "m",
                    _ => Lit(b.Constant),
                };
                return $"new HkValueArg({name}, {value})";
        }
    }

    private string ConditionExpression(Condition c)
    {
        var access = template.Parameter(c.Parameter) is { } p ? Access(p.Name) : "null";
        return c.Op switch
        {
            ConditionOp.IsTrue => $"HkCondition.IsTrue({access})",
            ConditionOp.IsFalse => $"!HkCondition.IsTrue({access})",
            ConditionOp.EqualsValue => $"HkCondition.EqualsValue({access}, {Lit(c.Value)})",
            ConditionOp.NotEqualsValue => $"!HkCondition.EqualsValue({access}, {Lit(c.Value)})",
            ConditionOp.IsEmpty => $"HkCondition.IsEmpty({access})",
            _ => $"!HkCondition.IsEmpty({access})",
        };
    }
}
